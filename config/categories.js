// Quick index maps
const CATEGORY_MAP = new Map();
const ALIAS_MAP = new Map();

for (const cat of CATEGORIES) {
  CATEGORY_MAP.set(cat.id, cat);
  if (cat.slug && cat.slug !== cat.id) {
    ALIAS_MAP.set(cat.slug.toLowerCase(), cat);
  }
  if (Array.isArray(cat.aliases)) {
    for (const a of cat.aliases) {
      ALIAS_MAP.set(String(a).toLowerCase(), cat);
    }
  }
}

function resolveCategory(key) {
  if (!key) return null;
  const raw = String(key).trim().toLowerCase();
  if (CATEGORY_MAP.has(raw)) return CATEGORY_MAP.get(raw);
  if (ALIAS_MAP.has(raw)) return ALIAS_MAP.get(raw);
  const normalized = raw.replace(/[_\s]+/g, '-');
  if (CATEGORY_MAP.has(normalized)) return CATEGORY_MAP.get(normalized);
  if (ALIAS_MAP.has(normalized)) return ALIAS_MAP.get(normalized);
  return null;
}

module.exports = {
  CATEGORIES,
  resolveCategory,
};
