const Announcement = require('../models/Announcement');

const CATEGORY_LABELS = {
  properties: 'Properties',
  automobile: 'Vehicles',
  'consumer-electronics': 'Electronics',
  electronics: 'Electronics',
  'bedding-comfort': 'Bedding Products',
  bedding: 'Bedding Products',
  finance: 'Finance & Loan Offers',
  'finance-lending': 'Finance & Loan Offers',
};

const CATEGORY_LINKS = {
  properties: '/categories/properties',
  automobile: '/categories/automobile',
  'consumer-electronics': '/categories/consumer-electronics',
  electronics: '/categories/consumer-electronics',
  'bedding-comfort': '/categories/bedding-comfort',
  bedding: '/categories/bedding-comfort',
  finance: '/categories/finance-lending',
  'finance-lending': '/categories/finance-lending',
};

/**
 * Automatically records or updates a product-addition notification in the backend.
 * Called whenever new products are added, imported, or approved.
 */
async function recordProductAddition(category, count = 1, metadata = {}) {
  try {
    const catKey = (category || 'properties').toLowerCase().trim();
    const catLabel = CATEGORY_LABELS[catKey] || 'Products';
    const catLink = CATEGORY_LINKS[catKey] || '/categories';

    // Look for an auto-generated announcement created in the last 24 hours for this category
    const oneDayAgo = new Date(Date.now() - 24 * 60 * 60 * 1000);
    let existing = await Announcement.findOne({
      category: catKey,
      isAutoGenerated: true,
      updatedAt: { $gte: oneDayAgo },
    });

    if (existing) {
      existing.productCount = (existing.productCount || 0) + count;
      existing.message = `🔥 ${existing.productCount} new ${catLabel} added today! Explore newly verified listings.`;
      existing.link = catLink;
      existing.active = true;
      await existing.save();
      return existing;
    }

    // Otherwise create a fresh announcement
    const message = count > 1
      ? `🔥 ${count} new ${catLabel} added! Explore newly verified listings.`
      : `🔥 New ${catLabel.slice(0, -1)} listed! Explore newly verified listings.`;

    const newAnnouncement = await Announcement.create({
      message,
      type: 'product_update',
      category: catKey,
      productCount: count,
      link: catLink,
      isAutoGenerated: true,
      active: true,
      badgeText: 'NEW ADDITION',
      priority: 5,
    });

    return newAnnouncement;
  } catch (err) {
    console.error('Error recording product announcement:', err.message);
    return null;
  }
}

