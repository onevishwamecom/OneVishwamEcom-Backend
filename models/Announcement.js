const mongoose = require('mongoose');

const announcementSchema = new mongoose.Schema(
  {
    message: {
      type: String,
      required: [true, 'Announcement message is required'],
      trim: true,
      maxlength: [300, 'Message cannot exceed 300 characters'],
    },
    type: {
      type: String,
      enum: ['offer', 'product_update', 'alert', 'general'],
      default: 'general',
    },
    link: {
      type: String,
      trim: true,
      default: '',
    },
    active: {
      type: Boolean,
      default: true,
      index: true,
    },
    isAutoGenerated: {
      type: Boolean,
      default: false,
    },
    category: {
      type: String,
      trim: true,
      default: '',
    },
    productCount: {
      type: Number,
      default: 0,
    },
    priority: {
      type: Number,
      default: 0,
    },
    badgeText: {
      type: String,
      trim: true,
      default: '',
    },
  },
  {
    timestamps: true,
  }
);

// Index for high-performance public active announcements query
announcementSchema.index({ active: 1, priority: -1, updatedAt: -1 });

module.exports = mongoose.model('Announcement', announcementSchema);

