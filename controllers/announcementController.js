const Announcement = require('../models/Announcement');
const asyncHandler = require('../utils/asyncHandler');
const ApiResponse = require('../utils/ApiResponse');
const ApiError = require('../utils/ApiError');
const { recordProductAddition, seedDefaultAnnouncementsIfEmpty } = require('../services/announcementService');

// @desc    Get active announcements for website top ribbon
// @route   GET /api/announcements
// @access  Public
const getPublicAnnouncements = asyncHandler(async (req, res) => {
  await seedDefaultAnnouncementsIfEmpty();

  const announcements = await Announcement.find({ active: true })
    .sort({ priority: -1, updatedAt: -1 })
    .limit(10)
    .lean();

  new ApiResponse(200, { announcements }, 'Active ribbon announcements fetched').send(res);
});

// @desc    Get all announcements (Admin portal)
// @route   GET /api/announcements/admin
// @access  Private (Admin Only)
const getAllAnnouncements = asyncHandler(async (req, res) => {
  const { type, active } = req.query;
  const filter = {};

  if (type && type !== 'all') {
    filter.type = type;
  }
  if (active !== undefined && active !== 'all') {
    filter.active = active === 'true';
  }

  const announcements = await Announcement.find(filter)
    .sort({ priority: -1, updatedAt: -1 })
    .lean();

  const total = announcements.length;
  const activeCount = announcements.filter((a) => a.active).length;
  const autoGeneratedCount = announcements.filter((a) => a.isAutoGenerated).length;

  new ApiResponse(
    200,
    {
      announcements,
      stats: { total, activeCount, autoGeneratedCount },
    },
    'All announcements fetched'
  ).send(res);
});

// @desc    Create new announcement (Admin portal)
// @route   POST /api/announcements/admin
// @access  Private (Admin Only)
const createAnnouncement = asyncHandler(async (req, res) => {
  const { message, type = 'general', link = '', active = true, priority = 0, badgeText = '' } = req.body;

  if (!message || !message.trim()) {
    throw new ApiError(400, 'Announcement message is required');
  }

  const announcement = await Announcement.create({
    message: message.trim(),
    type,
    link: link.trim(),
    active: Boolean(active),
    priority: Number(priority) || 0,
    badgeText: badgeText.trim(),
    isAutoGenerated: false,
  });

  new ApiResponse(201, { announcement }, 'Announcement created successfully').send(res);
});

// @desc    Update existing announcement (Admin portal)
// @route   PUT /api/announcements/admin/:id
// @access  Private (Admin Only)
const updateAnnouncement = asyncHandler(async (req, res) => {
  const { id } = req.params;
  const { message, type, link, active, priority, badgeText } = req.body;

  const announcement = await Announcement.findById(id);
  if (!announcement) {
    throw new ApiError(404, 'Announcement not found');
  }

  if (message !== undefined) announcement.message = message.trim();
  if (type !== undefined) announcement.type = type;
  if (link !== undefined) announcement.link = link.trim();
  if (active !== undefined) announcement.active = Boolean(active);
  if (priority !== undefined) announcement.priority = Number(priority) || 0;
  if (badgeText !== undefined) announcement.badgeText = badgeText.trim();

  await announcement.save();

  new ApiResponse(200, { announcement }, 'Announcement updated successfully').send(res);
});

// @desc    Toggle active state (Admin portal)
// @route   PATCH /api/announcements/admin/:id/toggle
// @access  Private (Admin Only)
const toggleAnnouncement = asyncHandler(async (req, res) => {
  const { id } = req.params;
  const announcement = await Announcement.findById(id);
  if (!announcement) {
    throw new ApiError(404, 'Announcement not found');
  }

  announcement.active = !announcement.active;
  await announcement.save();

  new ApiResponse(200, { announcement }, `Announcement ${announcement.active ? 'activated' : 'deactivated'}`).send(res);
});

// @desc    Delete announcement (Admin portal)
// @route   DELETE /api/announcements/admin/:id
// @access  Private (Admin Only)
const deleteAnnouncement = asyncHandler(async (req, res) => {
  const { id } = req.params;
  const announcement = await Announcement.findByIdAndDelete(id);
  if (!announcement) {
    throw new ApiError(404, 'Announcement not found');
  }

  new ApiResponse(200, { id }, 'Announcement deleted successfully').send(res);
});

// @desc    Simulate/Trigger automated product addition announcement (e.g. 3 new properties)
// @route   POST /api/announcements/admin/simulate-addition
// @access  Private (Admin Only)
const simulateProductAddition = asyncHandler(async (req, res) => {
  const { category = 'properties', count = 3 } = req.body;
  const announcement = await recordProductAddition(category, Number(count) || 1);

  new ApiResponse(200, { announcement }, `Logged addition of ${count} ${category}`).send(res);
});

module.exports = {
  getPublicAnnouncements,
  getAllAnnouncements,
  createAnnouncement,
  updateAnnouncement,
  toggleAnnouncement,
  deleteAnnouncement,
  simulateProductAddition,
};

